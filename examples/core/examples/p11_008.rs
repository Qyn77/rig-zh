// BEGIN DOCUMENTATION BLOCK
use rig::message::ToolName;
use rig::tool::{DynamicTool, ToolExecutionError, ToolOutput};


let echo = DynamicTool::new(
    ToolName::new("echo")?,
    "Repeat the input text back",
    json!({
        "type": "object",
        "properties": { "text": { "type": "string" } },
        "required": ["text"]
    }),
    |args| {
        Box::pin(async move {
            let text = args["text"]
                .as_str()
                .ok_or_else(|| ToolExecutionError::invalid_args("`text` must be a string"))?;
            Ok(ToolOutput::text(text))
        })
    },
);


let agent = AgentBuilder::new(OpenAI::from_env()?.completion(openai::GPT_5_5))
    .dynamic_tool(echo)
    .build();
// END DOCUMENTATION BLOCK
